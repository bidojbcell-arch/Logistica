-- RutaRD core schema: courier accounts are created as pending by default.
-- No client-provided user metadata is trusted for role or approval status.

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  phone text not null default '',
  role text not null default 'courier' check (role in ('admin', 'courier')),
  approval_status text not null default 'pending' check (approval_status in ('pending', 'approved', 'rejected')),
  approved_at timestamptz,
  approved_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.delivery_zones (
  id text primary key,
  name text not null,
  zone_type text not null check (zone_type in ('Provincia', 'Municipio', 'Sector')),
  province text not null,
  municipality text not null,
  delivery_fee numeric(12, 2) not null default 0 check (delivery_fee >= 0),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.products (
  id text primary key default gen_random_uuid()::text,
  name text not null,
  default_price numeric(12, 2) not null default 0 check (default_price >= 0),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.orders (
  id bigint generated by default as identity primary key,
  tracking_token uuid not null unique default gen_random_uuid(),
  customer_name text not null,
  customer_phone text not null default '',
  address text not null,
  map_link text not null default '',
  product_id text references public.products(id) on delete set null,
  product_name text not null default '',
  quantity integer not null default 1 check (quantity > 0),
  unit_price numeric(12, 2) not null default 0 check (unit_price >= 0),
  zone_id text references public.delivery_zones(id) on delete set null,
  zone_name text not null default '',
  delivery_fee numeric(12, 2) not null default 0 check (delivery_fee >= 0),
  total numeric(12, 2) generated always as (quantity * unit_price + delivery_fee) stored,
  courier_id uuid references public.profiles(id) on delete set null,
  courier_name text not null default 'Sin asignar',
  status text not null default 'Pendiente' check (status in ('Pendiente', 'Asignado', 'En camino', 'Llegando', 'Entregado', 'No entregado', 'Cancelado')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.courier_locations (
  courier_id uuid primary key references public.profiles(id) on delete cascade,
  latitude double precision not null check (latitude between -90 and 90),
  longitude double precision not null check (longitude between -180 and 180),
  accuracy_meters double precision,
  recorded_at timestamptz not null default now()
);

create index orders_courier_status_created_idx on public.orders (courier_id, status, created_at desc);
create index orders_created_at_idx on public.orders (created_at desc);
create index products_active_name_idx on public.products (is_active, name);
create index delivery_zones_active_name_idx on public.delivery_zones (is_active, name);
create index courier_locations_recorded_at_idx on public.courier_locations (recorded_at desc);

create schema if not exists private;
revoke all on schema private from public, anon, authenticated;
grant usage on schema private to authenticated;

create function private.is_approved_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles p
    where p.id = (select auth.uid())
      and p.role = 'admin'
      and p.approval_status = 'approved'
  );
$$;
revoke all on function private.is_approved_admin() from public, anon;
grant execute on function private.is_approved_admin() to authenticated;

