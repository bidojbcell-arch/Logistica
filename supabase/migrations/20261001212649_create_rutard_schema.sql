create function public.approve_courier(p_courier_id uuid, p_approve boolean)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not (select private.is_approved_admin()) then
    raise exception 'Only an approved administrator can approve couriers';
  end if;

  update public.profiles
  set approval_status = case when p_approve then 'approved' else 'rejected' end,
      approved_at = case when p_approve then now() else null end,
      approved_by = (select auth.uid()),
      updated_at = now()
  where id = p_courier_id and role = 'courier';

  if not found then
    raise exception 'Courier account was not found';
  end if;
end;
$$;
revoke all on function public.approve_courier(uuid, boolean) from public, anon;
grant execute on function public.approve_courier(uuid, boolean) to authenticated;

create function public.assign_order(p_order_id bigint, p_courier_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not (select private.is_approved_admin()) then
    raise exception 'Only an approved administrator can assign orders';
  end if;

  if not exists (
    select 1 from public.profiles p
    where p.id = p_courier_id and p.role = 'courier' and p.approval_status = 'approved'
  ) then
    raise exception 'Courier must be approved before receiving orders';
  end if;

  update public.orders
  set courier_id = p_courier_id,
      status = case when status = 'Pendiente' then 'Asignado' else status end,
      updated_at = now()
  where id = p_order_id;

  if not found then
    raise exception 'Order was not found';
  end if;
end;
$$;
revoke all on function public.assign_order(bigint, uuid) from public, anon;
grant execute on function public.assign_order(bigint, uuid) to authenticated;

create function public.get_tracking_info(p_tracking_token uuid)
returns table (
  order_id bigint,
  customer_name text,
  address text,
  status text,
  product_name text,
  quantity integer,
  courier_name text,
  courier_phone text,
  courier_latitude double precision,
  courier_longitude double precision,
  location_recorded_at timestamptz
)
language sql
stable
security definer
set search_path = ''
as $$
  select o.id, o.customer_name, o.address, o.status, o.product_name, o.quantity,
         p.full_name, p.phone, cl.latitude, cl.longitude, cl.recorded_at
  from public.orders o
  left join public.profiles p on p.id = o.courier_id
  left join public.courier_locations cl on cl.courier_id = o.courier_id
  where o.tracking_token = p_tracking_token;
$$;
revoke all on function public.get_tracking_info(uuid) from public;
grant execute on function public.get_tracking_info(uuid) to anon, authenticated;

